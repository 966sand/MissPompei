// 场景1：单个单词 + 同义词
export function buildSinglePrompt(word) {
  return `请分析英语单词「${word}」。

要求：
1. 给出该单词本身的：音标(IPA)、词性、中文意思、英文用法说明、2 个中英对照例句。
2. 给出 3-5 个最贴近的同义词，每个同样包含：音标、词性、中文意思、英文用法说明、2 个中英对照例句。
3. 给出该词与同义词的差异辨析，包含：
   - 双列速览（每个词一句话核心语义）
   - 对照例句（同一场景下分别用不同词造句，体会差异）
   - 互换性判断（何时只能用 A 不能用 B，用 ✓/✗ 标注正确与错误用法并说明规则）
   - 一句话记忆口诀/总结

只返回如下 JSON（不要任何额外文字）：
{
  "mode": "single",
  "primary": {
    "word": "${word}",
    "phonetic": "<IPA 音标>",
    "pos": "<词性，如 n.>",
    "cn_meaning": "<中文意思>",
    "usage": "<英文用法说明>",
    "examples": [
      {"en": "<例句>", "cn": "<中文翻译>"},
      {"en": "<例句>", "cn": "<中文翻译>"}
    ]
  },
  "synonyms": [
    {
      "word": "<同义词>",
      "phonetic": "<IPA 音标>",
      "pos": "<词性>",
      "cn_meaning": "<中文意思>",
      "usage": "<英文用法说明>",
      "examples": [
        {"en": "<例句>", "cn": "<中文翻译>"},
        {"en": "<例句>", "cn": "<中文翻译>"}
      ]
    }
  ],
  "analysis": {
    "quick_compare": [
      {"word": "${word}", "point": "<一句话核心语义>"},
      {"word": "<同义词>", "point": "<一句话核心语义>"}
    ],
    "contrast_examples": [
      {"scenario": "<场景描述>", "sentences": [
        {"word": "${word}", "en": "<例句>", "cn": "<中文翻译>"},
        {"word": "<同义词>", "en": "<例句>", "cn": "<中文翻译>"}
      ]}
    ],
    "exclusive_usage": [
      {"use_only": "${word}", "en": "<只能用 ${word} 的正确句子>", "cn": "<中文翻译>", "wrong": "<换成同义词的错误句子>", "rule": "<为什么>"},
      {"use_only": "<同义词>", "en": "<只能用该同义词的正确句子>", "cn": "<中文翻译>", "wrong": "<换成 ${word} 的错误句子>", "rule": "<为什么>"}
    ],
    "summary": "<一句话记忆口诀/总结>"
  }
}`;
}

// 场景2：多个单词对比
export function buildMultiPrompt(words) {
  const list = words.join('  ');
  return `请辨析以下英语单词（空格分隔）：
${list}

要求：
1. 每个单词分别给出：音标(IPA)、词性、中文意思、英文用法说明、2 个中英对照例句。
2. 给出整体对比：按「中文意思 / 用法 / 差异点」三个维度，把每个词并排列出。
3. 对每个单词，给出只能用它的例句（体现其不可替换性）。
4. 用一句话总结这几个词的根本区别。

只返回如下 JSON（不要任何额外文字）：
{
  "mode": "multi",
  "words": [
    {
      "word": "<单词>",
      "phonetic": "<IPA 音标>",
      "pos": "<词性>",
      "cn_meaning": "<中文意思>",
      "usage": "<英文用法说明>",
      "examples": [
        {"en": "<例句>", "cn": "<中文翻译>"},
        {"en": "<例句>", "cn": "<中文翻译>"}
      ]
    }
  ],
  "analysis": {
    "overall_table": {
      "dimensions": ["中文意思", "用法", "差异点"],
      "rows": [
        {"word": "<单词>", "cells": ["<中文意思>", "<用法>", "<差异点>"]}
      ]
    },
    "exclusive": [
      {"word": "<单词>", "examples": [
        {"en": "<只能用该词的例句>", "cn": "<中文翻译>", "note": "<说明>"}
      ]}
    ],
    "summary": "<一句话总结>"
  }
}`;
}

// 场景3：中文口语 → 地道英语口语
export function buildColloquialPrompt(cn) {
  return `把下面这句中文翻译成**英语母语者在真实生活/工作中会脱口而出的地道口语**：

「${cn}」

核心要求（很重要）：
1. 不要给出教科书式的书面翻译，要给母语者的口语说法。可以是习语、短语动词、省略句、寒暄套话。
2. 如果这句话在英语里有多个地道说法（不同语气/场合），translation 只给最通用、最自然的那一个。
3. 例句必须是真实口语场景里会说的话，长度以一口气能说完为准（一般不超过 15 个单词）。
4. key_points 只挑前三部分里**真正值得学**的重点词或固定短语（优先短语动词、习语、固定搭配）。绝对不要挑 the / a / is / that / this / it 这类功能词或单个虚词——挑出来的每一项都必须让中文学习者觉得「原来这个要这么用」。
5. scenes 要在不同场景里各造一个新句子，体现这个说法怎么活用在别处。
6. 所有中文解释都要口语化、直白，不要用「之」「其」这类书面词。

只返回如下 JSON（不要任何额外文字）：
{
  "mode": "colloquial",
  "zh": "${cn}",
  "translation": "<最地道的那一句英语口语>",
  "literal": "<按字面直译的英语（用来对比，说明为什么前者更地道）>",
  "examples": [
    {"en": "<地道例句1>", "cn": "<中文意思 + 一句话说明这句用在什么场合>"},
    {"en": "<地道例句2>", "cn": "<中文意思 + 场合说明>"},
    {"en": "<地道例句3>", "cn": "<中文意思 + 场合说明>"}
  ],
  "key_points": [
    {
      "term": "<重点单词或短语>",
      "kind": "phrase",
      "phonetic": "<IPA 音标，短语给重音位置即可，如 /ˈɡɪv ʌp/>",
      "cn": "<中文意思>",
      "note": "<用法解析：什么场合说、语气轻重、常见搭配或容易用错的地方>"
    }
  ],
  "scenes": [
    {"scene": "<使用场景，如 同事闲聊 / 赶时间 / 委婉拒绝>", "en": "<该场景下的新例句>", "cn": "<中文解读>"}
  ],
  "tip": "<一句话提醒：这句口语的语气、正式度，或中国人常犯的误用>"
}`;
}

// 场景4：入门英语短文推荐
export function buildReadingPrompt(page = 0, avoid = []) {
  const avoidLine = avoid.length
    ? `\n【硬性要求】以下主题已经被上一批用过，本批 5 篇必须**全部换掉**，一篇都不许重复：${avoid.join('、')}。请选择与它们完全不同的领域。`
    : '';
  return `请推荐 5 篇适合**英语初学者（A2 水平）**的纯英语短文。${avoidLine}

要求：
1. 主题面向入门领域：日常生活、职场沟通、旅行出行、购物点餐、社交寒暄、健康习惯、学习技巧、天气季节、兴趣爱好、邻里社区等。5 篇的主题要尽量分散，不要重复。
2. body 必须是**纯英语**，不允许出现任何中文字符。长度**严格控制在 320–450 个字符之间（含空格）**，超过 470 就算不合格——宁短勿长。分 2–3 个自然段，每段之间用 \\n\\n 分隔。
3. 语言要简单地道：以简单句和常见词为主，可包含少量对初学者有用的常用短语。避免生僻词和复杂从句。
4. title 用英语，不超过 8 个单词。
5. background 用中文写 1–2 句，介绍这个话题的背景或为什么英语里常这么讲。
6. reason 用中文写 1 句，说明为什么这篇适合入门（比如「句式短、全是高频词」）。
7. words 给出 3 个本文值得记的英语词或短语。

只返回如下 JSON（不要任何额外文字）：
{
  "mode": "reading",
  "articles": [
    {
      "title": "<英语标题>",
      "topic": "<中文主题标签，4 字以内>",
      "body": "<纯英语正文，300-450 字符，段落用 \\n\\n 分隔>",
      "background": "<中文背景介绍，1-2 句>",
      "reason": "<中文推荐理由，1 句>",
      "words": ["<词或短语>", "<词或短语>", "<词或短语>"]
    }
  ]
}`;
}
